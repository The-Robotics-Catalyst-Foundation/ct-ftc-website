const NORMALIZE_RE = /\b(town of|city of)\b/gi;

export function coordsForCity(city: string | undefined | null): [number, number] | null {
	if (!city) return null;
	const key = city.trim().toLowerCase().replace(NORMALIZE_RE, '').trim();
	return CT_TOWN_COORDS[key] ?? null;
}
